import logging
import hashlib
from typing import List, Dict, Any, Optional
from .models import Message, ToolCall, ToolResult, CheckpointData
from .checkpoint import CheckpointStore
from .sandbox import SubprocessSandbox

logger = logging.getLogger("agent_loop")


class DurableAgentLoop:
    """
    Executes a durable ReAct loop with transactional checkpoints.
    If the worker crashes mid-task, calling execute() with the same task_id
    reconstitutes state and resumes from the exact turn.
    """

    def __init__(
        self,
        checkpoint_store: CheckpointStore,
        sandbox: SubprocessSandbox,
        max_turns: int = 15
    ):
        self.checkpoint_store = checkpoint_store
        self.sandbox = sandbox
        self.max_turns = max_turns

    def execute(self, task_id: str, instruction: str) -> CheckpointData:
        logger.info(f"Starting or resuming execution for task [{task_id}]")

        # 1. Attempt State Recovery from Checkpoint Store
        existing_ckpt = self.checkpoint_store.load_latest_checkpoint(task_id)
        if existing_ckpt:
            logger.info(f"Resuming task [{task_id}] from turn {existing_ckpt.turn_index}")
            messages = existing_ckpt.messages
            start_turn = existing_ckpt.turn_index + 1
            scratchpad = existing_ckpt.scratchpad
        else:
            logger.info(f"Initializing brand-new task [{task_id}]")
            messages = [
                Message(role="system", content="You are a reliable software engineering agent. Solve the task step-by-step."),
                Message(role="user", content=instruction)
            ]
            start_turn = 1
            scratchpad = {}

        current_turn = start_turn
        while current_turn <= self.max_turns:
            logger.info(f"[Task {task_id}] Executing Turn {current_turn}/{self.max_turns}")

            # 2. Determine Action (Reasoning Step)
            # In production, this prompts the LLM with tools. Here we provide the deterministic loop logic.
            thought, tool_call = self._plan_step(instruction, messages, current_turn)

            messages.append(Message(
                role="assistant",
                content=thought,
                tool_calls=[tool_call] if tool_call else None
            ))

            if not tool_call:
                # Agent concluded task
                final_ckpt = CheckpointData(
                    task_id=task_id,
                    turn_index=current_turn,
                    status="COMPLETED",
                    messages=messages,
                    scratchpad=scratchpad
                )
                self.checkpoint_store.save_checkpoint(final_ckpt)
                logger.info(f"Task [{task_id}] successfully completed at turn {current_turn}")
                return final_ckpt

            # 3. Execute Tool via Sandboxed Subprocess
            tool_result = self._dispatch_tool(tool_call)
            messages.append(Message(
                role="tool",
                content=tool_result.output,
                tool_result=tool_result
            ))

            # 4. Transactional Checkpoint Persistence
            ckpt = CheckpointData(
                task_id=task_id,
                turn_index=current_turn,
                status="RUNNING",
                messages=messages,
                scratchpad=scratchpad
            )
            self.checkpoint_store.save_checkpoint(ckpt)
            current_turn += 1

        # Max turns exceeded without convergence
        timeout_ckpt = CheckpointData(
            task_id=task_id,
            turn_index=self.max_turns,
            status="FAILED",
            messages=messages,
            scratchpad=scratchpad
        )
        self.checkpoint_store.save_checkpoint(timeout_ckpt)
        logger.warning(f"Task [{task_id}] exceeded maximum step ceiling of {self.max_turns}")
        return timeout_ckpt

    def _plan_step(self, instruction: str, history: List[Message], turn: int) -> tuple[str, Optional[ToolCall]]:
        # Deterministic multi-step test plan for verification
        if turn == 1:
            thought = "I need to inspect the project directory to see existing source code."
            call = ToolCall(
                tool_name="bash_execute",
                arguments={"command": "dir || ls -la"},
                idempotency_key=hashlib.sha256(f"{turn}:dir".encode()).hexdigest()
            )
            return thought, call
        elif turn == 2:
            thought = "Creating an implementation script to address the user instruction."
            call = ToolCall(
                tool_name="write_file",
                arguments={"relative_path": "solution.py", "content": "# Solution generated by Durable Agent\nprint('Hello from Agent!')\n"},
                idempotency_key=hashlib.sha256(f"{turn}:write_file".encode()).hexdigest()
            )
            return thought, call
        elif turn == 3:
            thought = "Executing the created script to verify output correctness."
            call = ToolCall(
                tool_name="bash_execute",
                arguments={"command": "python solution.py"},
                idempotency_key=hashlib.sha256(f"{turn}:execute_python".encode()).hexdigest()
            )
            return thought, call
        else:
            thought = "All requirements verified. Task complete."
            return thought, None

    def _dispatch_tool(self, call: ToolCall) -> ToolResult:
        if call.tool_name == "bash_execute":
            return self.sandbox.execute_command(call.arguments.get("command", ""))
        elif call.tool_name == "write_file":
            return self.sandbox.write_file(call.arguments.get("relative_path", ""), call.arguments.get("content", ""))
        elif call.tool_name == "read_file":
            return self.sandbox.read_file(call.arguments.get("relative_path", ""))
        else:
            return ToolResult(tool_name=call.tool_name, output=f"Unknown tool {call.tool_name}", is_error=True)
